def normalize_bracket(bracket: str) -> str:
    """Normalize bracket notation by removing spaces and extra characters."""
    return bracket.replace(" ", "").replace(")", ")").replace("(", "(")


def bracket_to_canonical(bracket: str) -> str:
    """
    Convert Dan's bracket notation to our canonical forest notation.
    
    Dan's notation uses nested parentheses for a single rooted tree.
    Our notation uses the same but represents forests (multiple trees).
    """
    # Remove any trailing characters and normalize
    bracket = normalize_bracket(bracket)
    
    # The bracket notation should already be in canonical form
    # Just ensure it's properly formatted
    return bracket


def find_matching_forest(bracket: str, forests: List[RootedForest]) -> Optional[RootedForest]:
    """Find the forest that matches the given bracket notation."""
    target = normalize_bracket(bracket)
    
    for forest in forests:
        if forest.canonical() == target:
            return forest
    
    return None


def create_term_forest_mapping() -> Dict[int, Tuple[System5Term, Optional[RootedForest]]]:
    """
    Create a mapping between System 5 terms and rooted forests.
    
    Returns a dictionary mapping term number to (term, forest) tuple.
    """
    forests = list(get_system5_configurations())
    mapping = {}
    
    for term in SYSTEM5_TERMS:
        forest = find_matching_forest(term.bracket_notation, forests)
        mapping[term.number] = (term, forest)
    
    return mapping


# =============================================================================
# VIRTUAL IMAGE ANALYSIS
# =============================================================================

def identify_virtual_image_terms() -> List[System5Term]:
    """
    Identify the terms that correspond to virtual image configurations.
    
    Based on our analysis, virtual image configurations have exactly 3 trees.
    """
    forests = list(get_system5_configurations())
    virtual_image_terms = []
    
    for term in SYSTEM5_TERMS:
        forest = find_matching_forest(term.bracket_notation, forests)
        if forest and forest.tree_count() == 3:
            virtual_image_terms.append(term)
    
    return virtual_image_terms


def get_triadic_organization() -> Dict[Triad, List[System5Term]]:
    """Get terms organized by their triad association."""
    organization = {triad: [] for triad in Triad}
    
    for term in SYSTEM5_TERMS:
        if term.triad:
            organization[term.triad].append(term)
    
    return organization


