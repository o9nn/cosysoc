    print("=" * 80)
    
    mapping = create_term_forest_mapping()
    
    matched = 0
    unmatched = 0
    
    for num, (term, forest) in sorted(mapping.items()):
        print(f"\nT{num:02d}: {term.name}")
        print(f"     Bracket: {term.bracket_notation}")
        print(f"     Polarity: {term.polarity.value}")
        print(f"     Triad: {term.triad.value if term.triad else 'N/A'}")
        
        if forest:
            analysis = analyze_forest(forest)
            print(f"     Forest: {analysis.bracket_notation}")
            print(f"     Trees: {analysis.tree_count}, Sizes: {analysis.tree_sizes}, Depth: {analysis.max_depth}")
            matched += 1
        else:
            print(f"     Forest: NOT FOUND")
            unmatched += 1
    
    print("\n" + "=" * 80)
    print(f"SUMMARY: {matched} matched, {unmatched} unmatched")
    print("=" * 80)
    
    # Virtual image analysis
    print("\nVIRTUAL IMAGE TERMS:")
    print("-" * 40)
    for term in identify_virtual_image_terms():
        print(f"  T{term.number:02d}: {term.name}")
    
    # Triadic organization
    print("\nTRIADIC ORGANIZATION:")
    print("-" * 40)
    for triad, terms in get_triadic_organization().items():
        print(f"\n{triad.value}:")
        for term in terms:
            print(f"  T{term.number:02d}: {term.name}")


